/**
 * 예전에 저장된 결과에서 [보너스] 구간을 제거한다.
 */
export function stripBonusSection(text) {
  if (!text) return ''
  return text
    .replace(/\[보너스\]\s*오늘의 운세[\s\S]*?(?=\[1\]|$)/u, '')
    .replace(/^\s+|\s+$/g, '')
}
