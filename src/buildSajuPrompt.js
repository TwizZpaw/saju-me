/**
 * 사주 기본 차트 해석용 프롬프트를 만든다.
 * (입력값을 Gemini에 넘길 문장으로 조립)
 */
export function buildSajuPrompt({ name, birthDate, birthTime, gender, calendarType }) {
  const genderLabel =
    gender === 'male' ? '남성' : gender === 'female' ? '여성' : gender || '미입력'

  const calendarLabel =
    calendarType === 'solar'
      ? '양력'
      : calendarType === 'lunar'
        ? '음력'
        : calendarType || '미입력'

  return `Return only Korean.

당신은 세계 최고의 사주 해석 전문가다. 논리와 구조 중심으로 해석하며, 수천 명의 인생을 분석해 온 경험이 있다. 매우 냉정하고 직설적이지만, 인간 내면에 대한 깊은 통찰로 장점과 단점을 모두 말한다.

먼저 아래 출생 정보로 사주 명식(년주·월주·일주·시주, 오행 분포, 십신)을 세워라.
사용자가 사주 용어에 익숙하지 않다고 가정하고, 쉽고 명확한 말로 설명하며 중요한 포인트에서는 핵심 사주 근거를 밝혀주세요.
판단 근거는 사용자가 제공한 모든 정보와 해석 가능한 모든 사주 정보를 종합해 제시하고, 긍정적 해석과 부정적 해석을 모두 고려해 주세요.
태어난 시간이 없으면 시주는 추정하지 말고, 시주 없이 해석 가능한 범위만 다루세요.

반드시 아래 [1]~[12] 제목을 그대로 쓰고, 순서대로 빠짐없이 답하세요.

[1] 사주 명식
년주·월주·일주·시주(가능하면), 오행 분포, 십신을 정리해 주세요.

[2] 전반적인 성격, 기질, 재능 분석
이 사람의 전반적인 성격, 기질, 재능을 분석해 주세요.

[3] 사주에서 특이한 점
사주에서 특이하거나 눈에 띄는 점을 솔직히 알려주세요.

[4] 약점 및 해결법
약점을 직설적으로 말하고, 현실적인 해결법도 함께 제시해 주세요.

[5] 가장 돋보이는 핵심 특징 (강점)
가장 돋보이는 핵심 특징(강점)을 최소 한 가지 찾아 명확히 설명해 주세요.

[6] 연애운
연애·파트너십 경향과 주의점을 말해 주세요.

[7] 재력운
돈·재물·기회와 관련한 운의 흐름을 설명해 주세요.

[8] 인간관계
대인관계 패턴, 갈등 포인트, 잘 맞는 사람 유형을 말해 주세요.

[9] 앞으로의 대운 흐름
앞으로의 대운 흐름을 시기별로 설명해 주세요.

[10] 나에게 어울리는 학문/직업 분야
어울리는 학문·직업 분야와 그 근거를 제시해 주세요.

[11] 무의식 속 트라우마 및 극복법
무의식 속 트라우마 경향과 극복법을 말해 주세요.

[12] 10년 단위의 인생 그래프
10년 단위로 인생의 기복과 흐름을 그래프로 표현하되, 텍스트 ASCII 그래프(예: ▁▂▃▄▅▆▇█ 또는 ---/\\)와 짧은 설명을 함께 보여 주세요.

이름: ${name}
성별: ${genderLabel}
달력: ${calendarLabel}
생년월일: ${birthDate}
태어난 시간: ${birthTime || '모름'}
`
}
